pub fn step_icon(kind: &str) -> Icon {
    match kind {
        "read" => Icon::FileText,
        "image" => Icon::Image,
        "search" => Icon::Search,
        "list" => Icon::List,
        "command" => Icon::Terminal,
        "edit" => Icon::Pencil,
        "web" | "fetch" => Icon::Globe,
        "mcp" => Icon::Waypoints,
        "skill" => Icon::Zap,
        "agent" => Icon::Bot,
        "question" => Icon::CircleHelp,
        "wait" => Icon::Clock,
        _ => Icon::Wrench,
    }
}
