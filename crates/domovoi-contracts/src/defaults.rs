//! t3code default values (see `defaults/NOTICE.md`), each read into the record
//! it is a value of.
#![expect(clippy::disallowed_types, reason = "t3code's bundled default values: JSON files, each read into the record it is a value of")]

use serde::Deserialize;
use serde_json::Value;
use std::collections::BTreeMap;
use domovoi_model::typed::{
    ExecutionEnvironmentCapabilities, ProviderDriverKind, ResolvedKeybindingRule, ServerProviderContinuation, ServerProviderModel,
    ServerProviderSetup, ServerSettings,
};

const BUNDLED: &str = "bundled defaults are valid";

pub fn capabilities() -> ExecutionEnvironmentCapabilities {
    serde_json::from_str(include_str!("../defaults/capabilities.json")).expect(BUNDLED)
}

/// t3code's default keybindings as a fresh server resolves them
/// (`keybindings` of its `ServerConfig`).
pub fn keybindings() -> Vec<ResolvedKeybindingRule> {
    #[derive(Deserialize)]
    struct Resolved {
        keybindings: Vec<ResolvedKeybindingRule>,
    }
    serde_json::from_str::<Resolved>(include_str!("../defaults/keybindings.json")).expect(BUNDLED).keybindings
}

/// `ServerSettings` decoded from `{}`: every setting at its default.
pub fn settings() -> ServerSettings {
    serde_json::from_str(include_str!("../defaults/settings.json")).expect(BUNDLED)
}

/// The parts of a Codex or Claude provider entry (`ServerProvider`) that no
/// probe decides.
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ProviderDefaults {
    pub driver: ProviderDriverKind,
    pub display_name: String,
    /// Its `group_key` contains `/HOME`, to be replaced with the real home directory.
    pub continuation: ServerProviderContinuation,
    pub show_interaction_mode_toggle: bool,
    pub reports_context_window: bool,
    pub setup: ServerProviderSetup,
    pub models: Vec<ServerProviderModel>,
}

/// Static parts of the Codex / Claude provider entries, keyed by instance id
/// (`codex`, `claudeAgent`).
pub fn providers() -> BTreeMap<String, ProviderDefaults> {
    serde_json::from_str(include_str!("../defaults/providers.json")).expect(BUNDLED)
}

/// `ProviderCapabilities` reported on provider sessions, keyed by driver
/// (`codex`, `claudeAgent`, `opencode`, `pi`).
pub fn provider_capabilities() -> Value {
    serde_json::from_str(include_str!("../defaults/provider-capabilities.json")).expect("bundled defaults are valid JSON")
}

/// t3code's `DEFAULT_KEYBINDINGS` rules in their string form (`key`, `command`,
/// `when`), generated by `conformance/gen-keybinding-rules.ts`.
pub const KEYBINDING_RULES: &str = include_str!("../defaults/keybinding-rules.json");

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn file(text: &str) -> Value {
        serde_json::from_str(text).expect(BUNDLED)
    }

    /// Each record writes back the file it was read from: no default is lost or reworded on the way to a client.
    #[test]
    fn the_records_encode_back_to_the_bundled_files() {
        assert_eq!(json!(capabilities()), file(include_str!("../defaults/capabilities.json")));
        assert_eq!(json!(settings()), file(include_str!("../defaults/settings.json")));
        assert_eq!(json!(keybindings()), file(include_str!("../defaults/keybindings.json"))["keybindings"]);
        let sent = file(include_str!("../defaults/providers.json"));
        for (instance, defaults) in providers() {
            let sent = &sent[instance.as_str()];
            assert_eq!(json!(defaults.driver), sent["driver"]);
            assert_eq!(json!(defaults.display_name), sent["displayName"]);
            assert_eq!(json!(defaults.continuation), sent["continuation"]);
            assert_eq!(json!(defaults.show_interaction_mode_toggle), sent["showInteractionModeToggle"]);
            assert_eq!(json!(defaults.reports_context_window), sent["reportsContextWindow"]);
            assert_eq!(json!(defaults.setup), sent["setup"]);
            assert_eq!(json!(defaults.models), sent["models"]);
        }
    }
}
